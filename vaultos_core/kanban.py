"""Project tracker/tasks.yaml as a board the Obsidian Kanban plugin can open.

A generated, read-only file. tracker/tasks.yaml is the source of truth; `vaultos sync`
overwrites the board. Moving a card in Obsidian does not change a task.
"""

LANES = (
    ("Backlog", {None, "", "backlog", "todo", "idea"}),
    ("Ready", {"ready", "planned"}),
    ("In Progress", {"in_progress", "review"}),
    ("Blocked", {"blocked"}),
    ("Done", {"done"}),
    ("Dropped", {"dropped"}),
)

BANNER = ("<!-- Generated by `vaultos sync`. Do not edit — the source of truth is tracker/tasks.yaml.\n"
          "     vaultos sync가 만든 파일. 고치지 않는다 — 정본은 tracker/tasks.yaml. -->")


def _lane(status):
    for name, statuses in LANES:
        if status in statuses:
            return name
    return LANES[0][0]  # unknown status goes to Backlog, never hidden


def _clean(value):
    return str(value).replace("\n", " ").strip() if value not in (None, "") else ""


def _card(task):
    line = f"**{_clean(task.get('id')) or '?'}** {_clean(task.get('title')) or '(untitled)'}"
    extra = []
    if task.get("owner"):
        extra.append(f"\U0001F464 {_clean(task['owner'])}")
    if task.get("due"):
        extra.append(f"due {_clean(task['due'])}")
    if task.get("priority") and task["priority"] not in ("medium", "normal"):
        extra.append(f"P:{_clean(task['priority'])}")
    if extra:
        line += " — " + " · ".join(extra)
    return f"- [{'x' if task.get('status') == 'done' else ' '}] {line}"


def render(tasks):
    lines = ["---", "kanban-plugin: board", "---", "", BANNER, ""]
    lanes = {name: [] for name, _ in LANES}
    for task in tasks:
        lanes[_lane(str(task.get("status") or "").lower() or None)].append(task)
    for name, _ in LANES:
        lines += [f"## {name}", ""] + [_card(x) for x in lanes[name]] + [""]
    return "\n".join(lines).rstrip() + "\n"
